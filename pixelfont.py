# accented vowels (pinyin tone marks, Dutch/French accents): the lowercase
# vowels use rows 2-6, so the accent goes in rows 0-1
_ACCENTS = {
    "\u0304": (".###.", "....."),   # macron      a -> ā
    "\u0301": ("...#.", "..#.."),   # acute       a -> á
    "\u030c": (".#.#.", "..#.."),   # caron       a -> ǎ
    "\u0300": (".#...", "..#.."),   # grave       a -> à
    "\u0308": (".#.#.", "....."),   # diaeresis   a -> ä
    "\u0302": ("..#..", ".#.#."),   # circumflex  a -> â
}
_DOTLESS_I = "..#..|..#..|.##..|..#..|..#..|..#..|.###.|....."
def _accented():
    import unicodedata
    out = {}
    for base in "aeiou":
        rows = (_DOTLESS_I if base == "i" else _G[base]).split("|")
        for mark, (r0, r1) in _ACCENTS.items():
            ch = unicodedata.normalize("NFC", base + mark)
            if len(ch) == 1:
                out[ch] = "|".join([r0, r1] + rows[2:])
    # capitals: accent on top, letter squeezed into rows 2-6 (rows 0,1,3,5,6)
    for base in "AEIOU":
        rows = _G[base].split("|")
        small = [rows[0], rows[1], rows[3], rows[5], rows[6]]
        for mark, (r0, r1) in _ACCENTS.items():
            ch = unicodedata.normalize("NFC", base + mark)
            if len(ch) == 1:
                out[ch] = "|".join([r0, r1] + small + ["....."])
    # pinyin u-umlaut with a tone mark: show as plain ü (no room for both)
    for ch in "ǖǘǚǜ":
        out[ch] = out["ü"]
    return out
_G.update(_accented())

_ROWS = {ch: [row for row in pat.split("|")] for ch, pat in _G.items()}

def width(s):
    return max(0, len(s) * CELL_W - 1)

def text(draw, x, y, s, fill=0, scale=1):
    """Draw s with its top-left at (x, y). scale=2 doubles every pixel."""
    x, y = int(round(x)), int(round(y))
    for ch in s:
        rows = _ROWS.get(ch, _ROWS["?"])
        for ry, row in enumerate(rows):
            for rx, px in enumerate(row):
                if px == "#":
                    if scale == 1:
                        draw.point((x + rx, y + ry), fill=fill)
                    else:
                        draw.rectangle((x + rx * scale, y + ry * scale,
                                        x + rx * scale + scale - 1,
                                        y + ry * scale + scale - 1), fill=fill)
        x += CELL_W * scale

def wrap(s, max_width, max_lines=None):
    """Word-wrap s to lines no wider than max_width pixels."""
    per_line = max(1, (max_width + 1) // CELL_W)
    lines, cur = [], ""
    for word in s.split():
        while len(word) > per_line:              # break very long words
            if cur:
                lines.append(cur)
                cur = ""
            lines.append(word[:per_line])
            word = word[per_line:]
        trial = (cur + " " + word).strip()
        if len(trial) <= per_line:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    if max_lines and len(lines) > max_lines:
        lines = lines[:max_lines]
        last = lines[-1]
        if len(last) >= per_line:
            last = last[:per_line - 1]
        lines[-1] = last.rstrip(" .,;") + "…"
    return lines

def text_centered(draw, cx, y, s, fill=0):
    text(draw, cx - width(s) / 2, y, s, fill=fill)

def block(draw, x0, x1, y, s, fill=0, max_lines=None):
    """Wrap s between x0 and x1, centre each line, return the y below it."""
    for ln in wrap(s, x1 - x0, max_lines):
        text_centered(draw, (x0 + x1) / 2, y, ln, fill=fill)
        y += LINE_H
    return y
